/**
 * 拼生图提示词。顺序固定：角色 → 场景 → 融合 → 风格 → 构图。
 *
 * ★ 2026-10-11 加 `companion`：传了（= 买了旅行伙伴）就整体切到**双人**模式 ——
 *   角色块换成两个人 + 双人融合模板 + 双人否定项。**不传时逐字节等于从前**。
 * @param {{scene?:string, fusion?:string, style?:string, rare?:boolean, charStyle?:string, companion?:string|boolean}} p
 * @returns {string}
 */
export function buildImagePrompt({ scene, fusion, style, rare, charStyle, companion, foe, foeLook, regionName, rand, outfits = null, world = '', visual = '', tone = '', toneAvoid = '', camera = null, situation = '' } = {}) {
  const duo = Boolean(companion);
  // ★ 2026-10-14 服装系统：`outfits` = `{ 少女id: 服装id }`；不传 ⇒ 全部默认着装（与从前逐字一致）
  const parts = [duo ? duoCharacterBlock(companion, outfits) : composeCharacter('whale', outfits?.whale)];
  // 与地区画风正交的一维；双人时两人共用同一套画法（否则一张图里两种笔触）
  if (charStyle) parts.push(duo ? `人物画法（两位少女都按这个来）：${charStyle}` : `人物画法：${charStyle}`);
  const wl = worldLine({ work: regionName, world });
  if (wl) parts.push(wl);                      // ★ 世界基调（2026-10-18：景点卡也带，以前只有遭遇战带）
  const tl = toneLine({ tone, avoid: toneAvoid });
  if (tl) parts.push(tl);                      // ★ 影调（2026-10-18：管明度与光源，专治"太亮"）
  const sl = situationLine(situation);
  if (sl) parts.push(sl);                      // ★ 世界局势（2026-10-18 试点：泰拉）
  const sc = sanitizeScene(scene);
  if (sc) parts.push(`场景：${sc}`);
  if (visual) parts.push(`实景（她当时看到的）：${visual}`);   // ★ B 方案：她自己的可视短句
  // ★ `foe`（该地该遇到的敌手）非空时，抽选池里会多出两条"战斗构图"（见 BATTLE_ACTIONS）；
  //   同时带上**外观锚**（`foeLook`）与**作品锚**（`regionName`）——
  //   前者说"这东西长什么样"、后者说"这是哪个作品的"，免得被画成普通虫子 / 现代士兵
  parts.push(`融合：${fusion || (duo
    ? pickDuoFusion(rand, companion, foe, regionName, foeLook)
    : pickFusion(rand, foe, regionName, foeLook))}`);
  const cl = cameraLine(camera);
  if (cl) parts.push(cl);
  if (style) parts.push(styleLine(style));
  if (rare) parts.push(RARE_CARD_HINT);        // 稀有明信片：加质感
  parts.push(duo ? duoNegativeHint(companion) : NEGATIVE_HINT);
  // ★★ 手部/肢体约束**单独成行**，并且放在**最后一行**（结尾位置权重高）。
  //    原来它被拼在上一行否定项里 —— 一长段里塞了"文字/水印/体型/同框/解剖"五件事，
  //    实测压不住（用户反馈"手又崩了"）。单独成行是用户 2026-10-11 明确要求的做法。
  parts.push(EXPRESSION_HINT);
  parts.push(anatomyHint({ duo }));
  return fitPrompt(parts);
}


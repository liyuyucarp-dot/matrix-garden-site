export function buildPartnerPrompt({ partners = [], scene, fusion, style, rare, charStyle, foe, foeLook, regionName, rand, outfits = null, world = '', visual = '', tone = '', toneAvoid = '', camera = null, situation = '' } = {}) {
  const ids = (Array.isArray(partners) ? partners : [partners])
    .map((x) => normalizeCompanionId(x))
    .filter((id) => COMPANION_CHARACTER[id]);
  const [a, b] = [...new Set(ids)];                 // 同一位别出现两次（会画成双胞胎）
  if (!a || !b) return '';
  // ★ 2026-10-14 服装系统：两位伙伴**各自的**着装（这趟是她俩自己出门，鲸鱼不在画面里）
  const parts = [
    '【双人明信片：画面中是两位结伴同行的少女，同框出现、体型相当、都要完整入画】'
      + '第一位——' + composeCharacter(a, outfits?.[a]) + '；'
      + '第二位——' + composeCharacter(b, outfits?.[b]) + '；'
      + '画面里只有这两位少女、没有其他人（这是她俩自己出去玩的一趟），'
      + '一定要有"两人同行"的互动感（并肩走 / 一前一后 / 对视交谈 / 一起望向风景），'
      + '不要像两张贴纸那样各自站着互不相干'
  ];
  // 与地区画风正交的那一维；两位共用同一套画法（否则一张图里两种笔触）
  if (charStyle) parts.push(`人物画法（两位少女都按这个来）：${charStyle}`);
  const wlP = worldLine({ work: regionName, world });
  if (wlP) parts.push(wlP);                        // ★ 世界基调（2026-10-18：所有卡都带）
  const tlP = toneLine({ tone, avoid: toneAvoid });
  if (tlP) parts.push(tlP);
  const slP = situationLine(situation);
  if (slP) parts.push(slP);
  const sc = sanitizeScene(scene);
  if (sc) parts.push(`场景：${sc}`);
  if (visual) parts.push(`实景（她当时看到的）：${visual}`);
  parts.push(`融合：${fusion || pickPartnerFusion(rand, foe, regionName, foeLook)}`);
  const clP = cameraLine(camera);
  if (clP) parts.push(clP);
  if (style) parts.push(styleLine(style));
  if (rare) parts.push(RARE_CARD_HINT);
  parts.push(duoNegativeHint([a, b], { whale: false }));
  parts.push(EXPRESSION_HINT);
  parts.push(anatomyHint({ duo: true }));          // 手/肢体约束单独成行、放最后（权重高）
  return fitPrompt(parts);
}


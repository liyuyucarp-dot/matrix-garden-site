const safeKey = (k) => String(k).replace(/[^a-z0-9_]/gi, '_');

/**
 * 造一个"把图存进技能目录"的函数。
 * 为什么要复制：生图能力给的 filePath 在**系统临时目录**且会被自动清理，
 * 直接引用它 = 相册过几天变裂图。
 * @returns {(img:{filePath?:string,dataUrl?:string,mime?:string}) => Promise<string>} 返回落盘后的绝对路径
 */
export function makeImageSaver(chatKey, { subdir = 'photos', log } = {}) {
  return async function saveImage(img) {
    const dir = path.join(DATA_DIR, 'skills', 'travel-whale', subdir, safeKey(chatKey));
    fs.mkdirSync(dir, { recursive: true });
    const stamp = new Date().toISOString().replace(/[:.]/g, '-');
    const rand = Math.random().toString(36).slice(2, 6);

    // ① 优先复制本地文件（生图能力通常已把字节落盘，复制比解码 base64 快也更可靠）
    const src = String(img?.filePath ?? '').trim();
    if (src && src !== '(未能留档)' && fs.existsSync(src)) {
      const ext = path.extname(src) || '.jpg';
      const dst = path.join(dir, `${stamp}-${rand}${ext}`);
      fs.copyFileSync(src, dst);
      return dst;
    }

    // ② 退回 base64（能力返回 dataUrl 时）
    const raw = String(img?.dataUrl ?? '').trim();
    const b64 = raw.startsWith('base64://') ? raw.slice('base64://'.length)
      : raw.startsWith('data:') ? raw.slice(raw.indexOf(',') + 1)
        : '';
    if (b64) {
      const mime = String(img?.mime || 'image/jpeg');
      const ext = mime.includes('png') ? '.png' : mime.includes('webp') ? '.webp' : '.jpg';
      const dst = path.join(dir, `${stamp}-${rand}${ext}`);
      fs.writeFileSync(dst, Buffer.from(b64, 'base64'));
      return dst;
    }

    throw new Error('图片既没有本地路径也没有 base64 内容');
  };
}


// 矩阵庭院 · 明信片（文案 + 配图）
//
// ── 为什么文案要独立提示词 ──────────────────────────────────────────────
//   群聊人设铁律是"一句话 1~10 字、不要小作文"。但明信片是**另一种载体** ——
//   它本来就是旅行日记。硬套群聊规则会写成"到了。挺好。"，完全没有明信片的
//   味道。所以这里走**独立提示词**：题字保持小鲸鱼口吻且短，感想放开到 ~50 字。
//
// ── 为什么"融合"要用固定模板，不让模型自由发挥 ──────────────────────────
//   景点是动态搜索来的，"小鲸鱼怎么进入这个场景"如果每次现编，画出来
//   十有八九是"一只鲸鱼杵在风景照前面"。所以把融合收敛成**固定语法**
//   （着地站姿 / 坐姿 / 探身 / 环绕 / 吉祥物比例），模型只从里面挑一个，
//   配合**固定角色描述**，一致性就守住了。
//
// ── 为什么要自己把图存一份 ──────────────────────────────────────────────
//   image-generate 能力返回的 filePath 在**系统临时目录**，而且它会
//   pruneLocal() 自动删旧图。直接存那个路径，过几天相册里全是裂图。
//   所以必须复制到技能自己的目录。


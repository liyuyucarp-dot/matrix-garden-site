/**
 * ★★ 2026-10-18（用户选定的 B 方案）：从**她刚写好的 `thought`** 里抽 1~2 个可视短句。
 *
 * 为什么用 thought：它和配图是同一张卡、同一件事，而且天生是"人眼所见"的视角
 *   ——「镀金的墙，宽得像海」「盔甲上的金箔被正午晒得发白」这种句子，比搜索来的
 *   78 字建筑规格更像画面。**它已经在出图之前生成**，所以这里不增加任何调用。
 *
 * 取法：先按**整句**打分（可视词多的那句更可能是一段景物描写），再从这句里挑
 *   2 个可视分句按原序拼 —— 句子级优先是为了**不把两段不相干的东西缝在一起**。
 *   ⚠️ 第一版是按分句打分，实测选出来的是「走到宫门前才知道自己有多小，
 *      被香炉的烟熏得直打喷嚏」—— 有"烟"也有"门"，但不是画面。所以加了
 *      "知道/觉得/想/笑"这类**非视觉动词的扣分**。
 */
const VISUAL_CHAR = /[色光影子烟雾雨雪云风灰白金红蓝绿黑褐墙塔阶门柱穹顶砖石木铁玻璃灯潮浪沙漠林山峰海河湖岸冰火星夜人群旗甲剑书布织花草树]/g;
const NON_VISUAL = /(知道|觉得|想|说|笑|哭|怕|开心|喜欢|舍不得|嫌)/;
export function visualFromThought(thought, max = 56) {
  const s = String(thought || '').replace(/[「」“”"'‘’]/g, ' ');
  const sentences = s.split(/[。！？；\n]/).map((x) => x.trim()).filter(Boolean);
  if (!sentences.length) return '';
  const scoreOf = (clause) => {
    const hits = (clause.match(VISUAL_CHAR) || []).length;
    return hits * 1.5 + (clause.length >= 8 ? 0.5 : 0) - (NON_VISUAL.test(clause) ? 1.5 : 0);
  };
  const rank = sentences.map((sentence, i) => {
    const clauses = sentence.split(/[，、]/).map((x) => x.trim()).filter((x) => x.length >= 3);
    const best = clauses.map(scoreOf).sort((a, b) => b - a).slice(0, 2);
    const total = best.reduce((a, b) => a + b, 0);
    return { sentence, clauses, i, total };
  }).filter((x) => x.total > 0);
  if (!rank.length) return '';
  rank.sort((a, b) => (b.total - a.total) || (a.i - b.i));
  const top = rank[0];
  const picked = top.clauses.map((c) => ({ c, sc: scoreOf(c) }))
    .filter((x) => x.sc > 0)
    .sort((a, b) => b.sc - a.sc)
    .slice(0, 2)
    .sort((a, b) => top.clauses.indexOf(a.c) - top.clauses.indexOf(b.c))
    .map((x) => x.c);
  return picked.join('，').slice(0, max);
}

/**
 * 提示词总预算。
 *
 * ⚠️ `image-generate` 的 `MAX_PROMPT_CHARS` 是**硬闸**，超了直接拒（"prompt 太长"）。
 *   实测：三人合照卡在加世界行**之前**就已经 **2199 字** —— 也就是说它本来就画不出来，
 *   只是还没遇到过"同行 3 人"的趟。2026-10-18 把那个闸抬到 4000（这是我们自己的
 *   保险值，不是接口上限），这里同步设 3600，并保留一条**降级链**防止无限增长。
 *   裁剪顺序（先丢最不值钱的）：场景原文缩到 46 字 → 去掉风格解释 → 去掉场景原文 → 去掉实景。
 */
export const PROMPT_LIMIT = 3600;
function fitPrompt(parts, limit = PROMPT_LIMIT) {
  let arr = parts.filter((x) => typeof x === 'string' && x.trim());
  const len = () => arr.join('\n').length;
  if (len() <= limit) return arr.join('\n');
  const shrinkScene = () => {
    const i = arr.findIndex((p) => p.startsWith('场景：'));
    if (i >= 0) arr[i] = arr[i].slice(0, 46);
  };
  const dropStyleHint = () => {
    const i = arr.findIndex((p) => p.startsWith('风格：'));
    // 风格行形如「风格：X（解释…）」；去掉末尾那段括号解释，只留风格名
    if (i >= 0) arr[i] = arr[i].replace(/（[^（）]*）\s*$/, '');
  };
  const drop = (prefix) => {
    const i = arr.findIndex((p) => p.startsWith(prefix));
    if (i >= 0) arr.splice(i, 1);
  };
  shrinkScene();
  if (len() <= limit) return arr.join('\n');
  dropStyleHint();
  if (len() <= limit) return arr.join('\n');
  drop('场景：');
  if (len() <= limit) return arr.join('\n');
  drop('实景');
  if (len() <= limit) return arr.join('\n');
  drop('影调');                    // 最后才丢：它是治"太亮"的那一行
  return arr.join('\n');
}

/** 把两条战斗动作按"当前人物 + 当地敌手 + 作品 + 外观"实例化；没有 foe 就返回空池（= 不参与抽选）。 */
function battlePool(who, foe, work, look = '', outcome = 'draw') {
  const f = String(foe || '').trim();
  if (!f) return [];
  const w = String(work || '').trim();
  const anchor = w ? WORLD_ANCHOR.replace(/\{work\}/g, w) : '';
  const lk = String(look || '').trim();
  const lookLine = lk ? `\n${FOE_LOOK_PREFIX}${lk}` : '';
  const pool = BATTLE_ACTIONS_BY_OUTCOME[outcome] || BATTLE_ACTIONS_BY_OUTCOME.draw;
  return pool.map((t) => t
    .replace(/\{who\}/g, who).replace(/\{foe\}/g, f) + anchor + lookLine);
}


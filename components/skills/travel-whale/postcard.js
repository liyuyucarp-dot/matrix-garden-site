/**
 * 这一趟该拿哪几位少女的定妆照（**纯函数**）。
 * @param {object} o
 * @param {string} o.companion 这一张同框的那位旅伴 id（可为空串 ⇒ 单人）
 * @param {string[]} o.partners 闲置伙伴「自己去玩」那趟的伙伴 id（画面里两位伙伴、鲸鱼在家）
 * @param {string[]} o.party 回家卡的同行全员 id（**不含鲸鱼**；≥2 位才构成合照）
 * @returns {string[]} 去重后的 id 列表，顺序即出场顺序
 */
export function refIdsFor({ companion = null, partners = [], party = [] } = {}) {
  const partyIds = (Array.isArray(party) ? party : []).map((x) => String(x ?? '').trim()).filter(Boolean);
  const partnerIds = (Array.isArray(partners) ? partners : []).map((x) => String(x ?? '').trim()).filter(Boolean);
  const list = [];
  if (partyIds.length >= 2) {
    list.push('whale', ...partyIds);            // 回家卡：全体合照（含她本人）
  } else if (partnerIds.length >= 2) {
    list.push(...partnerIds);                   // 伙伴出游：鲸鱼留守在家，画面里只有伙伴
  } else {
    list.push('whale');                         // 常规：她本人……
    const c = String(companion ?? '').trim();
    if (c) list.push(c);                        // ……± 这一张同框的那位
  }
  return [...new Set(list)];
}

/**
 * 人物画法 → 参考图的比例档（**纯函数**）。
 * ★ 只有 `CHARACTER_STYLES` 里那条「Q版…」走 Q 版定妆，其余四条（标准比例／半写实／
 *   绘本／赛璐璐）都是正比。用 `includes` 而不是全等 —— 将来再加一条"Q版××"也自动跟上。
 * ⚠️ 传进来的必须是**这一张实际抽到的那个 charStyle**（`composePostcard` 里是 `p.charStyle`），
 *    不能另掷一次骰子：两边的骰子一旦不同步，就会"按正比画、喂 Q 版图"。
 */
export function refRatioOf(charStyle) {
  return String(charStyle ?? '').includes('Q版') ? 'q' : 'pro';
}

/** 定妆参考图目录 —— 与 `chats` / `photos` 同级，放在宿主的**真实数据目录**下。 */
export function refsDir() {
  return path.join(DATA_DIR, 'skills', 'travel-whale', 'refs');
}

/**
 * 把 id 列表转成**真实存在**的定妆照绝对路径（缺的静默跳过 ⇒ 退回纯文生图）。
 * @param {object} o
 * @param {string[]} o.ids 出场少女 id
 * @param {'q'|'pro'} o.ratio 比例档
 * @param {string} [o.dir] 覆盖目录（单测用；不传则用 `refsDir()`）
 * @returns {string[]} 存在的文件路径（可能为空数组）
 */
export function pickRefPaths({ ids = [], ratio = 'pro', dir = null } = {}) {
  const base = dir || refsDir();
  const out = [];
  for (const id of (Array.isArray(ids) ? ids : [])) {
    const key = String(id ?? '').trim();
    if (!key) continue;
    const p = path.join(base, `${key}--${ratio}.jpg`);
    try {
      if (fs.existsSync(p)) out.push(p);
    } catch { /* 探测失败就当没有这张，别让它打断整张明信片 */ }
  }
  return out;
}


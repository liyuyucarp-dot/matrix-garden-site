/**
 * ★★★ 拼「**旅行合照**」的生图提示词（回家卡用）。
 *
 * 与 `buildPartnerPrompt`（两位伙伴自己出门那趟）的区别：**鲸鱼少女在画面里**（第一位），
 * 且人数是 N（≥3）—— 她 ＋ 这一趟同行的旅伴。
 *
 * @param {{members?:string[], scene?:string, style?:string, fusion?:string, rare?:boolean,
 *          charStyle?:string, foe?:string, foeLook?:string, regionName?:string,
 *          rand?:()=>number, outfits?:object}} p
 * @returns {string} 人数 < 3 时返回**空串** ⇒ 调用方据此回落原来的单人/双人路径
 */
export function buildTripGroupPrompt({
  members = [], scene, style, fusion, rare, charStyle,
  foe, foeLook, regionName, rand = Math.random, outfits = null, world = '', visual = '', tone = '', toneAvoid = '', camera = null, situation = ''
} = {}) {
  const ids = [...new Set((Array.isArray(members) ? members : [members])
    .map((x) => normalizeCompanionId(x))
    .filter((id) => id === 'whale' || COMPANION_CHARACTER[id]))];
  const k = ids.length;
  if (k < 3) return '';                      // 少于 3 人 ⇒ 交给原来的单人/双人构图

  const foeText = String(foe || '').trim();
  const head = `【旅行合照：横板照片，画面中是${cnNum(k)}位少女结伴同行，同框出现、体型相当、全都要完整入画】`;
  const blocks = ids.map((id, i) => `${i === 0 ? '第一位' : `第${cnOrd(i + 1)}位`}——${composeCharacter(id, outfits?.[id])}`);

  const parts = [head + '；' + blocks.join('；')];
  // ⚠️ 顺序 2026-10-18 调整：`charStyle` 挪到**风格之前**。原来是「风格 → 人物画法」，
  //   把人画法放在后面 ⇒ 它压过风格，整张图（含背景）都按日系动漫走 —— 这正是
  //   泰拉那张被画成"明亮白城"的权重原因之一。
  if (charStyle) parts.push(`人物画法（所有少女都按这个来）：${charStyle}`);
  const wlG = worldLine({ work: regionName, world });
  if (wlG) parts.push(wlG);
  const tlG = toneLine({ tone, avoid: toneAvoid });
  if (tlG) parts.push(tlG);
  const slG = situationLine(situation);
  if (slG) parts.push(slG);
  const sc = sanitizeScene(scene);
  if (sc) parts.push(`场景：${sc}`);                       // ★ 景点由调用方给（用户约束②）
  if (visual) parts.push(`实景（她当时看到的）：${visual}`);
  parts.push(`姿势：${pickTripGroupPose(rand, Boolean(foeText))}`);   // ★ 按 foe 分叉（用户约束③）
  parts.push(`融合：${fusion || (foeText
    ? battlePool(`${cnNum(k)}位少女`, foeText, regionName, foeLook)[0] || ''
    : TRIP_GROUP_FUSIONS[Math.min(TRIP_GROUP_FUSIONS.length - 1, Math.floor(rand() * TRIP_GROUP_FUSIONS.length))])}`);
  const clG = cameraLine(camera);
  if (clG) parts.push(clG);
  if (style) parts.push(styleLine(style));
  if (rare) parts.push(RARE_CARD_HINT);
  parts.push(tripGroupNegativeHint(k, { foe: Boolean(foeText) }));
  parts.push(tripGroupAnatomyHint(k));                    // 解剖约束单独成行、放最后（权重高）
  return fitPrompt(parts);
}

/**
 * 抽 N 人同行的融合模板（`composePostcard` 用，让**文案与配图共用同一个 fusion**）。
 * 有 foe ⇒ 从战斗池里抽（`who` 传"N 位少女"）；没有 ⇒ 从旅途经历池里抽。
 */
export function pickTripGroupFusion(rand = Math.random, n = 3, foe = '', work = '', look = '') {
  const k = Math.max(3, Number(n) || 3);
  const foeText = String(foe || '').trim();
  const pool = foeText
    ? battlePool(`${cnNum(k)}位少女`, foeText, work, look)
    : TRIP_GROUP_FUSIONS;
  if (!pool.length) return '';
  return pool[Math.min(pool.length - 1, Math.floor(rand() * pool.length))];
}

/**
 * ★★ 2026-10-14 图鉴图（稀有特产那件东西的配图）—— **谁带回来的谁捧着**。
 *
 * 原来这段提示词由 `index.js` 手拼、固定用 `WHALE_CHARACTER`（鲸鱼捧着）。
 * 但伙伴那趟（`sideTrip`）是**两位伙伴自己出门**带回来的，而且
 *   ⚠️ **两趟互相独立**（tick 里 `state.trip` 与 `state.sideTrip` 是两个并列的 if，
 *      注释原话："鲸鱼在途时，留在家的伙伴照样能出门"）⇒ 伙伴到家那一刻，
 *      **她本人可能还在外面**。"她捧着展示"于是经常是荒谬的。
 * 所以按趟分流：有两位 `partners` 就画那两位，否则才是鲸鱼。
 *
 * @param {{name?:string, partners?:string[], scene?:string, style?:string, outfits?:object, charStyle?:string,
 *   world?:string, visual?:string, regionName?:string, tone?:string, toneAvoid?:string, situation?:string}} p
 * @returns {string} 生图提示词（调用方直接丢给 imageGen）
 */
export function buildSouvenirPrompt({ name = '', partners = [], scene, style, outfits = null, charStyle = '', world = '', visual = '', regionName = '', tone = '', toneAvoid = '', situation = '' } = {}) {
  const ids = (Array.isArray(partners) ? partners : [partners])
    .map((x) => normalizeCompanionId(x))
    .filter((id) => COMPANION_CHARACTER[id]);
  const [a, b] = [...new Set(ids)];                // 同一位别出现两次（会画成双胞胎）
  const duo = Boolean(a && b);
  const parts = [];
  if (duo) {
    // ★ 2026-10-14 服装系统：谁带回来的谁捧着 —— 着装也各自取
    parts.push('【双人图鉴图：画面中是两位结伴同行的少女，同框出现、体型相当、都要完整入画】'
      + '第一位——' + composeCharacter(a, outfits?.[a]) + '；'
      + '第二位——' + composeCharacter(b, outfits?.[b]) + '；'
      + '画面里只有这两位少女、没有其他人（这是她俩自己出去玩带回来的东西）');
  } else {
    parts.push(composeCharacter('whale', outfits?.whale));
  }
  // ★ 2026-10-26：人物画法这一维原来**只有明信片有**（`buildImagePrompt` / 双人 / 伙伴图都带），
  //   图鉴图漏了 ⇒ 同一趟里明信片是一种笔触、特产图可能是另一种。补上，位置与明信片一致
  //   （紧跟角色块，权重高）。
  if (charStyle) parts.push(`人物画法${duo ? '（两位少女都按这个来）' : ''}：${charStyle}`);
  // ⚠️ "捧"这个动作**只交给一位** —— 两位同时捧一样东西必然催生多手
  //   （同 `buildPartnerPrompt` 的托盘处理：那样东西只能有一双手碰）。
  parts.push(`动作：${duo ? '走在前面那位双手捧着' : '双手捧着'}「${name}」`);
  const wlS = worldLine({ work: regionName, world });
  if (wlS) parts.push(wlS);
  const tlS = toneLine({ tone, avoid: toneAvoid });
  if (tlS) parts.push(tlS);
  const slS = situationLine(situation);
  if (slS) parts.push(slS);
  if (scene) parts.push(`场景：${scene}`);
  if (visual) parts.push(`实景（她当时看到的）：${visual}`);
  if (style) parts.push(styleLine(style));
  parts.push(`构图：以「${name}」为主体${duo ? '，两位少女分列两侧一同看向它' : '，只拿这一样东西'}，居中半身特写，无文字水印`);
  parts.push(duo ? duoNegativeHint([a, b], { whale: false }) : NEGATIVE_HINT);
  parts.push(EXPRESSION_HINT);
  parts.push(anatomyHint({ duo }));                // 手/肢体约束单独成行、放最后（权重高）
  return fitPrompt(parts);
}

/**
 * 拼文案提示词。
 * @param {{city,country,spot,style,seq,total,whaleName,timeText,battle,foe,foeLook}} p
 *   `battle` = 这一张抽中的是**遭遇战**（由 composePostcard 判定，不在这里猜）
 * @returns {string}
 */
/**
 * 题字上限（字数）—— **提示词与截断共用一个口径**。
 *   平时 12 字；「话多」模式（小书虫本人 / 藏书阁）20 字；学到「博览群书」30 字。
 * ⚠️ 这两个地方一旦各写一份，就会"要到 30 字却被切回 20"（2026-10-13 实抓过一次）。
 */
/**
 * 把超长题字切到 <= capN 字，**优先落在标点/空白上**（别把词切一半）。
 *
 * 为什么要它（2026-10-23）：原来 `caption.slice(0, capN)` 是纯字数硬切，
 *   实测切出过「核动力破冰船压碎浮冰，它们俩在船头冻成冰」—— 原句是"冻成冰棍"，
 *   最后一个字被切掉，读起来像句子断在半路。这是「文风怪」里最刺眼的一条。
 *
 * 规则：从 capN 往回找最近的标点/空白；位置必须在后半段（>= 55% 上限），
 *   否则宁可用满上限硬切 —— 免得切出一个只剩半句的短题字。
 */
export function cutCaptionAtBoundary(text, capN) {
  const src = String(text || '');
  const limit = Math.max(1, Number(capN) || 0);
  if (src.length <= limit) return src;
  const BOUNDS = '，。、；：？！,.;:!?…—～·)）」』】 ';
  const win = src.slice(0, limit + 1);
  // 55% 太严：20 字上限时 floor=11，而「核动力破冰船压碎浮冰，」的逗号在 10 ⇒ 仍会硬切成
  // 「…它们俩在船头冻成冰」（"冰棍"少一个字）。降到 40% ⇒ 那个逗号（10/20=50%）就能被用上。
  // 代价是偶尔题字比上限短一截 —— 但"短而完整"远好过"长而断字"。
  const floor = Math.max(6, Math.floor(limit * 0.4));
  for (let i = win.length - 1; i >= floor; i -= 1) {
    if (BOUNDS.includes(win[i])) {
      const cut = win.slice(0, i).trim();
      if (cut.length >= 6) return cut;
    }
  }
  return src.slice(0, limit);
}

export function captionCapOf(p = {}) {
  const want = Number(p?.captionCap);
  if (Number.isFinite(want) && want > 0) return Math.floor(want);
  return p?.longForm ? 20 : 12;
}

